// Reproducible browser-only vendor build. npm ci --ignore-scripts, then
// npm run vendor:html. Ordinary unpacked installs need neither npm nor a build.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root, stdin: { contents: 'export { parse } from "parse5";', resolveDir: root, sourcefile: 'parse5-entry.js' },
  bundle: true, platform: 'browser', format: 'esm', target: 'chrome106', write: false,
  legalComments: 'inline', charset: 'utf8',
  banner: { js: '// Generated by scripts/vendor-html-parser.mjs; do not edit. See THIRD_PARTY.txt.' },
});
const notices = [];
for (const name of ['parse5', 'entities']) {
  const base = path.join(root, 'node_modules', name);
  const pkg = JSON.parse(await readFile(path.join(base, 'package.json'), 'utf8'));
  notices.push(`${name} ${pkg.version}\n${pkg.repository?.url ?? pkg.repository ?? ''}\n\n${await readFile(path.join(base, 'LICENSE'), 'utf8')}`);
}
for (const [name, contents] of [['parse5.js', result.outputFiles[0].text], ['THIRD_PARTY.txt', notices.join('\n\n---\n\n')]]) {
  const destination = path.join(root, 'extension/vendor', name);
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== contents) throw new Error(`Vendor output differs: ${name}`);
  } else {
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, contents);
  }
}
console.log(process.argv.includes('--check') ? 'Vendor bundle and licenses match locked dependencies.' : 'Generated browser parser and third-party licenses.');
